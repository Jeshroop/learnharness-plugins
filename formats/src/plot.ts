// Turning y = f(x) into SVG paths: sampling that breaks at gaps and asymptotes,
// a robust y range, and evenly spaced axis ticks. Pure functions.

export type Point = [number, number];
export type Path = Point[];
export interface View { x: [number, number]; y: [number, number]; width: number; height: number }

export const SAMPLES = 240;

function quantileRange(values: number[], q = 0.05): [number, number] {
	const sorted = [...values].sort((a, b) => a - b);
	const at = (p: number) => sorted[Math.min(sorted.length - 1, Math.max(0, Math.round(p * (sorted.length - 1))))]!;
	return [at(q), at(1 - q)];
}

/** Sample the curve, starting a new path where it is undefined or jumps across the view (an asymptote).
 *  Given the view's y range, a jump of more than a quarter of the view that is still there at 16× finer
 *  sampling is an asymptote too, however wide the curve's own range is (tan(x) + x^4 in a narrow view). */
export function samplePaths(fn: (x: number) => number, [x0, x1]: [number, number], samples = SAMPLES, viewY?: [number, number]): Path[] {
	const raw: (Point | null)[] = [];
	for (let i = 0; i <= samples; i++) {
		const x = x0 + ((x1 - x0) * i) / samples;
		let y: number;
		try { y = fn(x); } catch { y = Number.NaN; }
		raw.push(Number.isFinite(y) ? [x, y] : null);
	}
	const finite = raw.filter((p): p is Point => p !== null);
	if (!finite.length) return [];
	const [lo, hi] = quantileRange(finite.map(p => p[1]));
	const jump = Math.max(hi - lo, 1e-6) * 2;
	const limit = viewY ? (viewY[1] - viewY[0]) / 4 : Number.POSITIVE_INFINITY;
	const pole = (a: Point, b: Point): boolean => {
		let previous = a[1];
		for (let k = 1; k <= 16; k++) {
			let y: number;
			try { y = k === 16 ? b[1] : fn(a[0] + ((b[0] - a[0]) * k) / 16); } catch { y = Number.NaN; }
			if (!Number.isFinite(y) || Math.abs(y - previous) > limit) return true;
			previous = y;
		}
		return false;
	};
	const paths: Path[] = [];
	let current: Path = [];
	for (const point of raw) {
		const previous = current[current.length - 1];
		const step = point && previous ? Math.abs(point[1] - previous[1]) : 0;
		if (!point || step > jump || (step > limit && pole(previous!, point))) {
			if (current.length) paths.push(current);
			current = point ? [point] : [];
			continue;
		}
		current.push(point);
	}
	if (current.length) paths.push(current);
	return paths;
}

/** A y range that ignores the extreme values near asymptotes, padded a little. */
export function fitY(paths: Path[], fallback: [number, number] = [-5, 5]): [number, number] {
	const ys = paths.flat().map(p => p[1]);
	if (!ys.length) return fallback;
	let [lo, hi] = quantileRange(ys);
	if (hi - lo < 1e-6) { lo -= 1; hi += 1; }
	const pad = (hi - lo) * 0.15;
	return [lo - pad, hi + pad];
}

const px = (value: number) => (Number.isFinite(value) ? value.toFixed(1) : "0");

/** SVG path data in view coordinates; far-off values are clamped so the numbers stay sane. */
export function toSvgPath(paths: Path[], view: View): string {
	const [x0, x1] = view.x, [y0, y1] = view.y;
	const sx = (x: number) => ((x - x0) / (x1 - x0)) * view.width;
	const sy = (y: number) => Math.min(view.height * 3, Math.max(-view.height * 2, view.height - ((y - y0) / (y1 - y0)) * view.height));
	return paths.filter(path => path.length > 1)
		.map(path => path.map(([x, y], i) => `${i ? "L" : "M"}${px(sx(x))} ${px(sy(y))}`).join(" "))
		.join(" ");
}

export const MAX_TICKS = 50;

/** Evenly spaced "nice" ticks (1, 2 or 5 × 10^k) inside the range — generated by index and capped,
 *  so a range far from zero (where the step is below the numbers' precision) can never loop forever. */
export function axisTicks([a, b]: [number, number]): number[] {
	const span = b - a;
	if (!(span > 0) || !Number.isFinite(span)) return [];
	const raw = span / 10;
	const magnitude = 10 ** Math.floor(Math.log10(raw));
	const step = [1, 2, 5, 10].find(m => m * magnitude >= raw)! * magnitude;
	const first = Math.ceil(a / step) * step;
	if (!Number.isFinite(first) || !(step > 0) || first + step === first) return [];
	const count = Math.min(Math.floor((b - first) / step + 1e-9) + 1, MAX_TICKS);
	return Array.from({ length: Math.max(0, count) }, (_, k) => Number((first + k * step).toFixed(10)) || 0);
}

export interface TickLabel { axis: "x" | "y"; x: number; y: number; text: string }

/** Number labels for the grid, placed along the axes (or the edges when an axis is out of view),
 *  skipping 0 and ticks too close to an edge to read. */
export function tickLabels(view: View): TickLabel[] {
	const { width: W, height: H } = view;
	const sx = (x: number) => ((x - view.x[0]) / (view.x[1] - view.x[0])) * W;
	const sy = (y: number) => H - ((y - view.y[0]) / (view.y[1] - view.y[0])) * H;
	const text = (t: number) => String(Number(t.toFixed(6)));
	const clamp = (value: number, lo: number, hi: number) => Math.min(hi, Math.max(lo, value));
	const labels: TickLabel[] = [];
	const xAt = clamp(sy(0) + 10, 9, H - 2);
	// Keep every k-th x label (aligned to 0) so that the widest label fits between neighbours: about
	// 5.5px per character at the 9px label size. Long numbers (100000, 0.0001) would otherwise run together.
	const xs = axisTicks(view.x);
	const tickStep = xs.length > 1 ? xs[1]! - xs[0]! : 1;
	const spacing = (tickStep / (view.x[1] - view.x[0])) * W;
	const every = Math.max(1, Math.ceil((Math.max(0, ...xs.map(t => text(t).length)) * 5.5 + 4) / spacing));
	for (const t of xs) {
		if (Math.round(t / tickStep) % every !== 0) continue;
		const x = sx(t);
		if (t !== 0 && x > 6 && x < W - 6) labels.push({ axis: "x", x, y: xAt, text: text(t) });
	}
	const yAt = clamp(sx(0) + 3, 2, W - 14);
	for (const t of axisTicks(view.y)) {
		const y = sy(t) + 3;
		if (t !== 0 && y > 9 && y < H - 3) labels.push({ axis: "y", x: yAt, y, text: text(t) });
	}
	return labels;
}
